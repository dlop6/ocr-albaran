const fs = require('fs');
const path = require('path');
const { PDFDocument } = require('pdf-lib');
const execa = require('execa');
const sharp = require('sharp');
const os = require('os');
const logger = require('../logger');

async function extractSinglePagePdf(sourcePdfPath, pageIndex, outPdfPath) {
  const bytes = fs.readFileSync(sourcePdfPath);
  const pdf = await PDFDocument.load(bytes);
  const newPdf = await PDFDocument.create();
  const [copied] = await newPdf.copyPages(pdf, [pageIndex]);
  newPdf.addPage(copied);
  const outBytes = await newPdf.save();
  fs.writeFileSync(outPdfPath, outBytes);
}

async function pdfToPngWithPdftocairo(pdfPath, outputDir) {
  if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir, { recursive: true });
  const outBase = path.join(outputDir, 'page');
  const args = ['-png', '-r', '300', pdfPath, outBase];
  await execa('pdftocairo', args);
  // pdftocairo names output like page-1.png
  const files = fs.readdirSync(outputDir).filter(f => f.toLowerCase().endsWith('.png'));
  if (files.length === 0) throw new Error('No PNG generated by pdftocairo');
  // return first png path
  return path.join(outputDir, files[0]);
}

async function pdfToPngWithSharp(pdfPath, outputPath) {
  // fallback: render first page using pdf-lib + sharp by extracting the page to a single-pg PDF
  // note: sharp cannot render PDF without libvips compiled with pdf support in some envs; this is a best-effort fallback.
  const tmpSingle = outputPath.replace(/\.png$/i, '.single.pdf');
  await extractSinglePagePdf(pdfPath, 0, tmpSingle);
  // convert with sharp (if supported)
  await sharp(tmpSingle, { density: 300 }).png().toFile(outputPath);
  fs.existsSync(tmpSingle) && fs.unlinkSync(tmpSingle);
  return outputPath;
}

async function runTesseractCli(imagePath, options = []) {
  // returns { text, elapsed }
  const start = process.hrtime();
  const { stdout } = await execa('tesseract', [imagePath, 'stdout', ...options], {
    env: { ...process.env, OMP_NUM_THREADS: '1' }
  });
  const elapsed = process.hrtime(start);
  const seconds = elapsed[0] + elapsed[1] / 1e9;
  return { text: stdout, seconds };
}

async function preprocImage(inputPath, outPath) {
  // grayscale, resize to width 2000 if smaller, denoise (median), adaptive-like threshold by emulating with linear contrast
  const img = sharp(inputPath).greyscale().normalise().sharpen({ sigma: 1.0 });
  await img.toFile(outPath);
  return outPath;
}

async function experiment() {
  const projectRoot = path.resolve(__dirname, '..', '..');
  const srcPdf = path.join(projectRoot, 'docs', 'EJEMPLO 3.pdf');
  if (!fs.existsSync(srcPdf)) {
    console.error('Source PDF not found:', srcPdf);
    process.exit(1);
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'ocr-exp-'));
  const singlePdf = path.join(tmpDir, 'page15.pdf');
  // page 15 is index 14
  await extractSinglePagePdf(srcPdf, 14, singlePdf);

  let pngPath;
  try {
    pngPath = await pdfToPngWithPdftocairo(singlePdf, tmpDir);
  } catch (err) {
    logger.warn('pdftocairo failed, falling back to sharp-based render:', err.message);
    pngPath = path.join(tmpDir, 'page15.png');
    await pdfToPngWithSharp(singlePdf, pngPath);
  }

  const results = {};

  // 1) Raw OCR (no preproc)
  try {
    const r = await runTesseractCli(pngPath, ['--psm', '6', '-l', 'spa']);
    results.raw = r;
  } catch (err) {
    results.raw = { error: err.message };
  }

  // 2) Preprocessed OCR
  const preprocPath = path.join(tmpDir, 'page15_preproc.png');
  await preprocImage(pngPath, preprocPath);
  try {
    const r = await runTesseractCli(preprocPath, ['--psm', '6', '-l', 'spa']);
    results.preproc = r;
  } catch (err) {
    results.preproc = { error: err.message };
  }

  // 3) Numbers-only (whitelist)
  try {
    const r = await runTesseractCli(preprocPath, ['--psm', '6', '-l', 'spa', '-c', 'tessedit_char_whitelist=0123456789.,-']);
    results.numbers = r;
  } catch (err) {
    results.numbers = { error: err.message };
  }

  const outFile = path.join(projectRoot, 'src', 'utils', 'ocr_experiment_results.json');
  fs.writeFileSync(outFile, JSON.stringify({ pngPath, tmpDir, results }, null, 2));
  console.log('Results saved to', outFile);
}

if (require.main === module) {
  experiment().catch(err => {
    console.error('Experiment failed:', err);
    process.exit(1);
  });
}

module.exports = { experiment };
